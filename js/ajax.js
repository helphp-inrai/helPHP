    /**
     * Processes JSON responses and handles UI feedback.
     * @param {Object|string} result - The AJAX result.
     */
    static process_json(result){
        if(H_generics.is_object(result)){

            if(result.reload_after_message){
                result.url = result.reload_after_message;
            }

            if(result.messages){
                H_ui.message_popup(result.messages , result.reload_after_message ? H_dom.reload_page.bind(result) : undefined );
            }

            if(result.url === H_constants.reload_noparams){
                H_dom.reload_page(result.url);
            }else{
                if(result.errors){
                    H_ui.message_popup(result.errors , result.reload_after_message ? H_dom.reload_page.bind(result) : undefined );
                }
            }
        }
    }

    /**
     * Processes the AJAX response.
     * @param {Event} event - The event object.
     */
    process_response(event){

        let type = this._xhr.getResponseHeader('Content-Type');

        //hide waiting modal
        if (!h.timer_modal_hidden && h.timer_modal){
            h.timer_modal.hide();
            h.timer_modal_hidden = true;
        }

        let result = this._xhr.responseText;
        if(type == 'application/json'){
            try{
                result = JSON.parse(result);
            }catch(e){
                result = this._xhr.responseText;
            }
        }

        this.update_response_data(event);

        if(this._xhr.status >= 400){
            console.error('Ajax Error',this._xhr);
            if(this._current_error_callback){
                this._current_error_callback(result , this);
            }

        }else{

            H_ajax_sender.process_json(result);

            if(this._dom_target && this._allow_target_update){

                if(H_generics.is_object(result)){

                    if(result.html !== undefined){
                        if(this._replace_dom_target){
                            H_dom.replace_element(this._dom_target , result.html);
                        }else{
                            H_dom.write_html(this._dom_target , result.html );
                        }

                    }

                }else if(H_generics.is_string(result)){
                    if(this._replace_dom_target){
                        H_dom.replace_element(this._dom_target , result);
                    }else{
                        H_dom.write_html(this._dom_target , result );
                    }
                }else{
                    console.warn('Wrong ajax result type',result);
                }
            }

            if(this._current_success_callback){
                this._current_success_callback(result , this);
            }
        }
    }
