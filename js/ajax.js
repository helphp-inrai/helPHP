        this.aborted = false;
        // handle pause of an upload
        this.paused = false;
        
        // calculate the number of slices (chunk)
        // var startTime = Date.now();
        this.last_chunk_sending_time = 0; // enregistre le dernier temps passé à envoyer un chunk
        this.chunk_start_time = Date.now();
        
        this.xhr = new XMLHttpRequest();
        
        // progress bytes by chunk
        this.last_progress_time = 0;
        
