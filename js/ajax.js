h.libs = h.libs || {};
/**
 * @class H_ajax
 * @classdesc
 * AJAX utility class for managing multiple concurrent AJAX requests, file uploads (including chunked uploads), 
 * progress tracking.<br><br>
 * Provides helpers for form serialization, file validation, and optionnaly TinyMCE image upload integration.<br>
 * We do not use javascript File API for a simple reason : we can't follow upload progress.<br>
 * Plus you can use async() await on succes or error if you need to do promisse like.<br>
 * This class is globaly instanciated as h.a but can be also found in h.libs.ajax.<br>
 * <br>
 * This class will use H_ajax_sender to create/manipulate the xhr object.<br>
 * And if there was some input files, formadata or blob sended, H.ajax_file will also be used.<br>
 * 
 * @example
 * basic usage :
 * automaticaly used by forms generated by helPHP server libs (h::form), you can create an ajax request like this:
 * ---------------------------------------------------------------
 *      let settings = {}; //our array of params 
 *      settings.url = ''; // the url to send you ajax request
 *      settings.data = { //the data key/pairs you want to send
 *          'param1':'value1' ,
 *          'param2':'value2' ,
 *          'param3':'value3',
 *          'action':'moduleaction'
 *          };
 *      settings.success = (res) => { //what to do with the result, set a callback etc...
 *          do something with res;
 *          };
 *      settings.error = (err) => { //what to do in case of error...
 *              do something with err;
 *              debugger;
 *          };
 *
 *      h.a.send(settings); //we send our request 
 *-----------------------------------------------------------------
 * @see https://developer.mozilla.org/en-US/docs/Using_files_from_web_applications
 * @returns {Mixed} content depending module return
 */
class H_ajax {
    constructor() {
        this.xhr_list = [];
        this._up_loaded_bytes = 0;
        this._up_total_bytes = 0;

        this._down_loaded_bytes = 0;
        this._down_total_bytes = 0;

        // if the total size is unknow, these values will contains the upload/download bytes values
        this._up_overload = 0;
        this._down_overload = 0;

        this._up_speed = 0;
        this._down_speed = 0;

        this._consecutive_streams = 10; // how many simultaneous ajax streams are allowed at the same time
        this._busy_stream_count = 0;
        this._running_stream_count = 0;

        this._stream_queue = [];
        // different queue for sending chunk faster

        this._last_data_time = 0;

        this._debug = false;
    }

    /**
     * Converts all inputs in a form to a JSON object.
     * @function
     * @param {HTMLFormElement} form - The form element to serialize.
     * @returns {Object} The serialized form data as an object.
     */
    form_to_obj(form) {
        var obj = {};
        var elements = form.querySelectorAll( "input, select, textarea" );
        for( var i = 0; i < elements.length; ++i ) {
            let element = elements[i];
            let name = element.name;
            let value = element.value;
            let tag_type = element.type.toLowerCase();
            if( name ) {
                if( tag_type == "checkbox" || tag_type == "radio"){
                    if(element.checked){
                        obj[ name ] = value;
                    }

                }else {
                    obj[ name ] = value;
                }
            }
        }

        return obj;
    }
    /**
     * Submits a form when a select element changes.
     * 
     * @function
     * @param {HTMLElement} selectDomElement - The select element.
     * @returns {boolean} True if submitted, false otherwise.
     */
    static submit_on_change(selectDomElement){

        if(selectDomElement.form){
            selectDomElement.form._submitter = selectDomElement;
            H_event.send_event(selectDomElement.form , 'submit');
        }else{
            return false;
        }
        return true;
    }

    /**
     * Converts a raw byte size into a human-readable string.
     * @param {number} size - The size in bytes.
     * @returns {string} Human-readable file size.
     */
    readable_file_size(size){
        let cnt = 0;
        let units = ['bytes','KB','MB','GB','TB'];
        while(size > 1024 && cnt < units.length-1){
            size /= 1024;
            cnt ++;
        }
        return size.toFixed(2)+' '+units[cnt];
    }

    /**
     * Checks if the file inputs respect the server limitations.
     * @function
     * @param {HTMLElement|FormData} dom_element - The DOM element or FormData to check.
     * @returns {boolean} True if valid, false otherwise.
     */
    static check_file_data(dom_element){
        var lst = [];
        
        if(H_generics.is_formdata(dom_element)){
            if(dom_element.entries){
                let data = dom_element.entries();
                let obj = data.next();
                while(undefined !== obj.value) {
                    let t = Object.prototype.toString.apply(obj.value[1]);
                    if(t == '[object File]'){
                        lst.push(obj.value[1]);
                    }
                    obj = data.next();
                }
            }else{
                console.log('Formdata.entries not supported !');
            }

        }else if(H_generics.is_dom_object(dom_element)){
            
            if (dom_element.tagName == 'INPUT' && dom_element.type == 'file' && dom_element.files){
                // if the given dom element is a FILE input, get its files
                lst = dom_element.files;

            }else if(dom_element.tagName == 'FORM'){
                // if the given dom element is a FORM, get all the files from the FILE inputs inside this form
                let elements = dom_element.elements;

                for(let i = 0; i < elements.length ; i++){
                    if(elements[i].type == 'file'){
                        for(let f = 0; f < elements[i].files.length ; f++){
                            lst.push(elements[i].files[f]);
                        }
                    }
                }
            }
        }

        let count = lst.length;
        let size = 0;
        for(let i = 0; i < count ;i++){
            size += lst[i].size;
        }
        let message = '';
        if(count > H_ajax.max_file_uploads){
            message += H_constants.get_text('too_many_files' , [count,H_ajax.max_file_uploads]); //'Too many files ('+count+')! Max = '+H_ajax.max_file_uploads;
        }
        if(size > H_ajax.max_upload_size){
            message += H_constants.get_text('too_heavy_files' , [H_ajax.readable_file_size(size),H_ajax.readable_file_size(H_ajax.max_upload_size)] ); //'Files are too heavy ('+H_ajax.readable_file_size(size)+')! Max = '+H_ajax.readable_file_size(H_ajax.max_upload_size);
        }

        if(message !== ''){
            H_ui.message_popup(message);
            return false;
        }else{
            return true;
        }
    }
    
    /**
     * TinyMCE image upload handler for AJAX image uploads.
     * called by Tinymce.php lib optionnaly
     * @function 
     * @param {Object} blobInfo - TinyMCE blobInfo object.
     * @param {Function} success - Success callback.
     * @param {Function} failure - Failure callback.
     */
    static tinymce_image_upload_handler(blobInfo, success, failure) {
        var xhr, formData;

        xhr = new XMLHttpRequest();
        xhr.withCredentials = false;
        xhr.open('POST', this.url);

        xhr.onload = function() {
            let json;

            if (xhr.status != 200) {
                failure('HTTP Error: ' + xhr.status);
                return;
            }

            try{
                json = JSON.parse(xhr.responseText);
            }catch(e){
                json = false;
                console.log(e);
            }

            if (!json || typeof json.location != 'string') {
                failure('Invalid JSON: ' + xhr.responseText);
                return;
            }

            success(json.location);
        };

        formData = new FormData();
        formData.append('file', blobInfo.blob(), blobInfo.filename());
        formData.set('action', this.action);

        console.log(blobInfo.filename());

        xhr.send(formData);
    }
    /**
     * Sleep utility function (async).
     * can be used to async / wait, 
     * @function
     * @param {number} ms - Milliseconds to sleep.
     * @returns {Promise<void>} Promise that resolves after the delay.
     * @example
     * await h.a.sleep(5000);
     * or
     * await H_anim.sleep(5000);
     */
    static sleep(ms) {
        return new Promise(resolve => setTimeout(resolve, ms));
    }
    /**
     * Gets the first available XHR sender or creates a new one.
     * @returns {H_ajax_sender} The sender instance.
     */
    get_sender(){

        let sender = null;

        for(let i = 0 , c = this.xhr_list.length; i < c ; i++){
            if(!this.xhr_list[i].busy){
                if(this._debug){
                    console.log('reuse sender ',i);
                }
                sender = this.xhr_list[i];
                break;
            }
        }

        if(sender === null){
            if(this._debug){
                console.log('create sender');
            }
            sender = new H_ajax_sender();
            this.xhr_list.push(sender);
        }

        sender._debug = this._debug;
        sender.ignore_file = false;

        return sender;
    }

    /**
     * Sends data according to the provided settings.
     * @param {Object} settings - AJAX settings.
     * @param {number} delay - Optional delay before sending.
     * @param {boolean} queue - Whether to queue the request.
     * @returns {H_ajax_sender|boolean} The sender or false if queued.
     */
    send(settings , delay , queue){

        let sender = this.get_sender();

        sender._debug = this._debug;

        if(this.running_stream_count <= this._consecutive_streams && !delay && !queue){
            sender.send(settings);
            return sender;
        }else{
            // if too many ajax stream are running, put the current in a waiting queue and run it later
            if(sender.set_data(settings)){
                if(delay){
                    sender._delayedSendTime = Date.now() + delay;
                }

                this.queue(sender);
            }
            return false;
        }
    }
    /**
     * Queues a sender for later execution.
     * @param {H_ajax_sender} sender - The sender to queue.
     */
    queue(sender){

        this._stream_queue.push(sender);

        if(!H_generics.is_function(sender)){
            sender._state = H_ajax_sender.STATE_QUEUED;
        }

        // try again to run the ajax call in 200ms
        if(this._queue_timer){
            clearTimeout(this._queue_timer);
        }

        this._queue_timer = setTimeout(this._process_queue.bind(this),200);
    }
    /**
     * Processes the AJAX queue.
     * @private
     */
    _process_queue(){

        if(this._queue_timer){
            clearTimeout(this._queue_timer);
        }

        // try to run the next ajax stream
        if(this._stream_queue.length){

            if(H_generics.is_function (this._stream_queue[0])){
                let f = this._stream_queue.shift();
                f();
            }else{

                if(this.running_stream_count <= this._consecutive_streams){

                        let sender = this._stream_queue[0];
                        let send = false;
                        if(sender._delayedSendTime){
                            if(Date.now() >= sender._delayedSendTime){
                                send = true;
                            }
                        }else{
                            send = true;
                        }
                        // test for the big file upload pause
                        if (sender._file && sender.pause_on_next_chunk){
                            send = false;
                        }
                        if(send){
                            sender = this._stream_queue.shift();
                            sender.send();
                        }

                }
            }
            this._queue_timer = setTimeout(this._process_queue.bind(this),200);
        }
    }

    /**
     * Computes the global progress for all running AJAX streams.
     */
    compute_progress() {
        let up_bytes_loaded = 0;
        let up_bytes_total = 0;

        let down_bytes_loaded = 0;
        let down_bytes_total = 0;

        let up_unknown_loaded = 0;
        let down_unknown_loaded = 0;

        this._up_overload = 0;
        this._up_speed = 0;
        this._down_speed = 0;
        this._speed = 0;

        this._down_zero_loaded = 0;
        this._down_zero_total = 0;

        for(let i = 0 , c = this.xhr_list.length; i < c ; i++){
            let x = this.xhr_list[i];
            if(x.busy){
                this._up_speed += x.up_speed;
                this._down_speed += x.down_speed;

                if(x._state == H_ajax_sender.STATE_UPLOADING){
                    this._speed += x.up_speed;
                }

                if(x._state == H_ajax_sender.STATE_DOWNLOADING){
                    this._speed += x.down_speed;
                }

                if(x.up_progress === null){
                    up_unknown_loaded += x.up_loaded_bytes;
                }else{
                    up_bytes_loaded += x.up_loaded_bytes;
                    up_bytes_total += x.up_total_bytes;
                }

                if(x.down_progress === null){
                    down_unknown_loaded += x.down_loaded_bytes;
                }else{
                    down_bytes_loaded += x.down_loaded_bytes;
                    down_bytes_total += x.down_total_bytes;

                    if(x._download_done && x.down_total_bytes === 0){
                        this._down_zero_loaded ++;
                        this._down_zero_total ++;
                    }
                }


            }
        }

        if(up_unknown_loaded + up_bytes_loaded > up_bytes_total){
            up_bytes_total = up_unknown_loaded + up_bytes_loaded;
            this._up_overload = up_unknown_loaded;
        }

        if(down_unknown_loaded + down_bytes_loaded > down_bytes_total){
            down_bytes_total = down_unknown_loaded + down_bytes_loaded;
            down_bytes_loaded += down_unknown_loaded;
            this._down_overload = down_unknown_loaded;
        }

        this._down_loaded_bytes = down_bytes_loaded;
        this._down_total_bytes = down_bytes_total;

        this._up_loaded_bytes = up_bytes_loaded;
        this._up_total_bytes = up_bytes_total;

        this._last_data_time = Date.now();
    }

    // indicates a temporary upload info until we had a correct update from the browser
    get up_overload(){
        return this._up_overload;
    }

    // indicates a temporary dowload info until we had an answer from the server
    get down_overload(){
        return this._down_overload;
    }

    // current overall upload speed
    get up_speed(){
        return this._up_speed;
    }

    // current overall download speed
    get down_speed(){
        return this._down_speed;   
    }

    // number of XHR doing something (initialization, upload, download, finalization ...)
    get busy_stream_count(){
        this._busy_stream_count = 0;
        for(let i = 0 , c = this.xhr_list.length; i < c ; i++){
            if(this.xhr_list[i].busy){
                this._busy_stream_count++;
            }
        }
        return this._busy_stream_count;
    }

    // number of transfer in progress
    get running_stream_count(){
        this._running_stream_count = 0;
        for(let i = 0 , c = this.xhr_list.length; i < c ; i++){
            if(this.xhr_list[i].running){
                this._running_stream_count++;
            }
        }
        return this._running_stream_count;
    }

    // overall upload progress (value between 0 and 1)
    get up_progress(){
        if(this._last_data_time === 0 || (Date.now() - this._last_data_time) > 100){
            this.compute_progress();
        }
        return this._up_total_bytes > 0 ? this._up_loaded_bytes / this._up_total_bytes : 0;
    }

    // overall download progress (value between 0 and 1)
    get down_progress(){
        if(this._last_data_time === 0 || (Date.now() - this._last_data_time) > 100){
            this.compute_progress();
        }
        return this._down_total_bytes > 0 ? this._down_loaded_bytes / this._down_total_bytes : this._down_zero_total > 0 ? this._down_zero_loaded / this._down_zero_total : 0;
    }

    // overall progression average
    get progress(){
        return (this.up_progress + this.down_progress) * 0.5;
    }

    // overall speed average
    get speed(){
        return this._speed;
    }
}

